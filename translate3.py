changed = 0
for f in files:
    try:
        orig = open(f, encoding='utf-8').read()
    except: continue
    new = orig
    for jp, zh in items:
        if jp in new:
            new = new.replace(jp, zh)
    if new != orig:
        open(f, 'w', encoding='utf-8').write(new)
        changed += 1

