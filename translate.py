# Build replacement list (longest first to avoid partial matches)
items = sorted(T.items(), key=lambda x: -len(x[0]))

def translate_text(text):
    for jp, zh in items:
        if jp in text:
            text = text.replace(jp, zh)
    return text

# Process all HTML files
files = ['index.html'] + glob.glob('games/*/index.html') + ['common/js/howto.js']
changed = 0
for f in files:
    try:
        orig = open(f, encoding='utf-8').read()
    except: continue
    new = translate_text(orig)
    if new != orig:
        open(f, 'w', encoding='utf-8').write(new)
        changed += 1
        print(f"  translated: {f}")

print(f"\nDone. {changed}/{len(files)} files modified.")
